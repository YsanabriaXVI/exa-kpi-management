) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;

CREATE TABLE `outbox_events` (
  `outbox_event_id` BIGINT NOT NULL AUTO_INCREMENT,
  `event_id` CHAR(36) NOT NULL,
  `event_type` VARCHAR(120) NOT NULL,
  `aggregate_type` VARCHAR(80) NOT NULL,
  `aggregate_id` VARCHAR(100) NOT NULL,
  `aggregate_version` INT UNSIGNED NOT NULL,
  `subject` VARCHAR(200) NOT NULL,
  `payload` JSON NOT NULL,
  `occurred_at` DATETIME(3) NOT NULL,
  `status` VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  `attempt_count` INT UNSIGNED NOT NULL DEFAULT 0,
  `next_attempt_at` DATETIME(3) NULL,
  `last_error` TEXT NULL,
  `published_at` DATETIME(3) NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NULL,
  PRIMARY KEY (`outbox_event_id`),
  UNIQUE INDEX `uq_outbox_events_event_id` (`event_id`),
  INDEX `ix_outbox_events_pending` (`status`, `next_attempt_at`, `occurred_at`),
  INDEX `ix_outbox_events_aggregate` (`aggregate_type`, `aggregate_id`, `aggregate_version`),
  CONSTRAINT `chk_outbox_events_event_type` CHECK (CHAR_LENGTH(TRIM(`event_type`)) > 0),
  CONSTRAINT `chk_outbox_events_aggregate_type` CHECK (CHAR_LENGTH(TRIM(`aggregate_type`)) > 0),
  CONSTRAINT `chk_outbox_events_aggregate_id` CHECK (CHAR_LENGTH(TRIM(`aggregate_id`)) > 0),
  CONSTRAINT `chk_outbox_events_subject` CHECK (CHAR_LENGTH(TRIM(`subject`)) > 0),
  CONSTRAINT `chk_outbox_events_version` CHECK (`aggregate_version` > 0),
  CONSTRAINT `chk_outbox_events_status` CHECK (`status` IN ('PENDING', 'PROCESSING', 'PUBLISHED', 'FAILED'))
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
